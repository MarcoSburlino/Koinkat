#!/usr/bin/env node
/**
 * Write dist/THIRD-PARTY-NOTICES.md for the single-file bundle.
 *
 * esbuild inlines the dependencies into dist/koinkat-mcp.mjs, and their
 * licences (MIT and similar) require the copyright and permission notice to
 * travel with every copy. `--legal-comments=eof` only keeps `/*!` comments,
 * which these packages do not use, so the notices are collected here from
 * the esbuild metafile: exactly the packages that ended up in the bundle.
 */
import { readFileSync, writeFileSync, existsSync, readdirSync } from 'node:fs';
import { join, resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const meta = JSON.parse(readFileSync(join(root, 'dist', 'meta.json'), 'utf8'));

/** node_modules/<name or @scope/name> directory of a bundled input path. */
function packageDir(input) {
  const at = input.lastIndexOf('node_modules/');
  if (at === -1) return null;
  const parts = input.slice(at + 'node_modules/'.length).split('/');
  const name = parts[0].startsWith('@') ? `${parts[0]}/${parts[1]}` : parts[0];
  return join(root, input.slice(0, at), 'node_modules', name);
}

const dirs = new Set();
for (const input of Object.keys(meta.inputs)) {
  const dir = packageDir(input);
  if (dir) dirs.add(dir);
}

const packages = [];
for (const dir of dirs) {
  const pkg = JSON.parse(readFileSync(join(dir, 'package.json'), 'utf8'));
  const licenceFile = readdirSync(dir).find((f) => /^(licen[cs]e|copying)(\.|$)/i.test(f));
  const text = licenceFile
    ? readFileSync(join(dir, licenceFile), 'utf8').replace(/\r\n/g, '\n').trim()
    : '';
  if (!text) throw new Error(`${pkg.name}@${pkg.version} ships no licence file`);
  packages.push({ name: pkg.name, version: pkg.version, licence: pkg.license ?? 'UNKNOWN', text });
}
packages.sort((a, b) => a.name.localeCompare(b.name) || a.version.localeCompare(b.version));

const lines = [
  '# koinkat-mcp bundle: third-party notices',
  '',
  'Generated by `npm run bundle` - do not edit. `koinkat-mcp.mjs` is',
  'GPL-3.0-or-later and inlines the packages below, each under its own licence.',
  '',
  ...packages.map((p) => `- \`${p.name}@${p.version}\` (${p.licence})`),
  '',
];
for (const p of packages) {
  lines.push(`### ${p.name}@${p.version}`, '', '```text', p.text, '```', '');
}
const out = join(root, 'dist', 'THIRD-PARTY-NOTICES.md');
if (!existsSync(join(root, 'dist'))) throw new Error('Run the bundle first.');
writeFileSync(out, lines.join('\n'));
console.log(`Wrote ${out} (${packages.length} packages)`);
